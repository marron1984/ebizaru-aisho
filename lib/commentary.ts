export function buildCommentary(a: Profile, b: Profile, d: CompatDetail): Commentary {
  const seed = pairSeed(a, b);

  const paragraphs: Paragraph[] = [
    kyuseiPara(a, b, d.starKind, seed),
    tongbianPara(d.tongbian, seed >> 1, a, b),
    branchPara(d.branchRelation, seed >> 2, a, b),
    zodiacPara(a, b, seed >> 3),
    numerologyPara(a, b, seed >> 4),
    seimeiPara(a, b, seed >> 5),
    fengshuiPara(a, b, seed >> 6),
  ];
  const mb = mbtiPara(a, b, seed >> 7);
  if (mb) paragraphs.push(mb);

  const synthesis = synthesisParagraphs(a, b, d, seed);

  const axes: AxisNote[] = [
    axisNote("仕事", d.work, d, a, b, seed),
    axisNote("対人", d.social, d, a, b, seed),
    axisNote("健康", d.health, d, a, b, seed),
    axisNote("金運", d.wealth, d, a, b, seed),
  ];

  return {
    headline: overallHeadline(a, b, d, seed),
    paragraphs,
    synthesis,
    axes,
    closing: closingLine(d, seed),
  };
}
