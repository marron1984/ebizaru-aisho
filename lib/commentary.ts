function pick<T>(arr: T[], seed: number): T {
  return arr[((seed % arr.length) + arr.length) % arr.length];
}

function pairSeed(a: Profile, b: Profile): number {
  const sa = Number(a.person.birth.replace(/\D/g, ""));
  const sb = Number(b.person.birth.replace(/\D/g, ""));
  return (sa ^ (sb * 2654435761)) >>> 0;
}

function tierOf(s: number): "exceptional" | "good" | "neutral" | "careful" | "low" {
  if (s >= 85) return "exceptional";
  if (s >= 70) return "good";
  if (s >= 55) return "neutral";
  if (s >= 40) return "careful";
  return "low";
}

function ageDiff(a: Profile, b: Profile): number {
  const ya = a.birth.y * 12 + a.birth.m;
  const yb = b.birth.y * 12 + b.birth.m;
  return Math.round((yb - ya) / 12); // a から見て b が +n 歳
}

